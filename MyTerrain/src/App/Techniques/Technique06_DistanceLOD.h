// 6-1. 거리 기반 LOD 지형1 (Distance LOD 1)
//
// 5번과 같은 펄린 노이즈 지형 위에서 시작한다(카메라·노이즈 파라미터·그리드 조작은
// PerlinControlComponent 가 그대로 맡는다). 여기에 얹는 것은 "청크마다 카메라까지의
// 거리를 재서, 먼 청크는 정점을 건너뛴 저해상도 인덱스로 그린다"는 부분이다.
//
//   - 5번 컬링이 "화면 밖을 안 그리는" 최적화였다면, LOD 는 "화면 안이지만 멀어서
//     작게 보이는 것을 대충 그리는" 최적화다. 둘은 겹치지 않으므로 같이 쓴다.
//   - 정점 버퍼는 여전히 하나만 그대로 쓴다. 레벨 L 은 정점을 2^L 칸씩 건너뛴
//     인덱스일 뿐이고, 모든 레벨의 인덱스를 메시를 구울 때 미리 만들어 하나의 정적
//     인덱스 버퍼에 이어 붙인다(원본의 약 1.33 배). 매 프레임 CPU 가 하는 일은
//     "청크마다 어느 구간을 그릴지 고르는 것"뿐이다.
//   - 레벨이 다른 청크가 맞닿는 경계에는 이음매(crack)가 생긴다. 이 기법은 그것을
//     숨기지 않고 보여준다 -- F 로 LOD 를 얼려놓고 경계까지 날아가면 틈으로 배경이
//     비치는 것을 직접 볼 수 있다. 제대로 된 해결(스티칭 / 지오머핑)은 6-2 의 주제다.
//   - J 로 이웃 레벨 차이를 1 이하로 제한하면 틈이 작아지지만 없어지지는 않는다.
//
//   [카메라] W/A/S/D 이동, E/Q 상하, 마우스 우클릭 드래그로 시점 회전,
//            휠로 이동 속도, Shift 가속, R 로 초기 위치 복귀
//   [노이즈] 위/아래로 항목 선택, 왼쪽/오른쪽으로 값 조절, N 합성 방식, M 시드 무작위, 0 기본값
//   [LOD]    L 켬/끔, K 레벨 색상, F 프리즈, J 이웃 레벨 제한, C 절두체 컬링, B 청크 박스,
//            , / . 청크 크기, ; / ' 기준 거리, U / I 레벨 수, 0 기본값
//   [그리드] + / - 로 분할 수, [ / ] 로 셀 크기, Tab 으로 표시 모드 전환
void BuildDistanceLODScene(Scene& scene);
