// 카메라 절두체 밖에 있는 덩어리는 통째로 건너뛰고 그린다"는 부분뿐이다.
//
//   - 정점 버퍼는 지금까지처럼 하나만 그대로 쓴다. 인덱스 버퍼만 리프별로 다시 정렬해서,
//     보이는 리프들만 모아 나눠 그린다 -- 그래서 리프 경계에 이음매(crack)가 생기지 않는다.
//   - 매 프레임 뷰-프로젝션 행렬에서 6개 평면을 뽑아(Frustum), 쿼드트리를 위에서부터 훑으며
//     절두체 밖 노드는 자식(그 아래 리프 전부)을 방문조차 하지 않는다.
//   - B 키로 보이는 리프들의 AABB 를 선으로 겹쳐 그려서, 카메라를 움직일 때 어떤 덩어리가
//     걸러지고 남는지 눈으로 바로 확인할 수 있다.
//
//   [카메라] W/A/S/D 이동, E/Q 상하, 마우스 우클릭 드래그로 시점 회전,
//            휠로 이동 속도, Shift 가속, R 로 초기 위치 복귀
//   [노이즈] 위/아래로 항목 선택, 왼쪽/오른쪽으로 값 조절, N 합성 방식, M 시드 무작위, 0 기본값
//   [쿼드트리] C 컬링 켬/끔, B 디버그 박스, , / . 리프 크기 줄이기/늘리기, 0 기본값
//   [그리드] + / - 로 분할 수, [ / ] 로 셀 크기, Tab 으로 표시 모드 전환
