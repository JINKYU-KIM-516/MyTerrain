class Scene;

// 6-2. 고급 거리 LOD 지형2 - 스티칭 & 지오머핑 (Advanced Distance LOD 2)
//
// 6-1 이 일부러 남겨둔 두 문제를 각각 푼다.
//
//   [이음매(crack)] 레벨이 다른 두 청크가 맞닿으면 세밀한 쪽에만 있는 경계 중간 정점이
//     거친 쪽 변 위에 떠서(T-junction) 틈이 벌어진다. 스티칭은 "세밀한 쪽이 거친 쪽에
//     맞춰 준다" -- 그 변의 홀수번째 경계 정점을 쓰지 않도록 테두리를 다시 엮는다.
//     거친 쪽은 손대지 않으므로 누가 누구에게 맞출지 하는 순환 의존이 없다.
//
//   [팝핑(popping)] 레벨이 바뀌는 순간 지형이 툭 튄다. 지오머핑은 전환 직전 구간에서
//     정점 높이를 "한 단계 거친 레벨에서의 높이" 쪽으로 서서히 끌어당긴다. 전환 시점에
//     두 메시가 기하적으로 완전히 같아지므로 전환이 보이지 않는다.
//     morph 계수를 청크가 아니라 정점 자신의 거리로 계산하는 것이 핵심이다 --
//     그래야 정점을 공유하는 두 청크가 같은 값을 얻어 경계가 어긋나지 않는다.
//
// 구현상 처음으로 정점 포맷(GridMesh::Vertex)과 BasicTerrain.hlsl 을 건드린 기법이다.
// 정점에 "레벨별 부모 높이" float4 가 붙었고, 정점 셰이더가 그쪽으로 높이를 lerp 한다.
// 지오머핑을 끄면 lerp 계수가 0 이 되어 1~6-1번 기법과 완전히 같은 결과가 나온다.
//
//   [카메라] W/A/S/D 이동, E/Q 상하, 마우스 우클릭 드래그로 시점 회전,
//            휠로 이동 속도, Shift 가속, R 로 초기 위치 복귀
//   [노이즈] 위/아래로 항목 선택, 왼쪽/오른쪽으로 값 조절, N 합성 방식, M 시드 무작위, 0 기본값
//   [6-2]    H 스티칭, G 지오머핑, V morph 시각화, O / P morph 폭
//   [LOD]    K 레벨 색상, F 프리즈, C 컬링, B 청크 박스,
//            , / . 청크 크기, ; / ' 기준 거리, U / I 레벨 수, 0 기본값
//   [그리드] + / - 로 분할 수, [ / ] 로 셀 크기, Tab 으로 표시 모드 전환
//
// 눈으로 확인하는 법:
//   - F 로 LOD 를 얼려놓고 레벨 경계까지 날아간 다음 H 를 껐다 켰다 하면
//     틈이 생겼다 사라졌다 한다.
//   - 카메라를 앞뒤로 천천히 움직이며 G 를 껐다 켰다 하면 팝핑이 사라지는 것이 보인다.
//   - V 를 켜면 어느 청크가 지금 morph 중인지(파랑 -> 빨강) 바로 보인다.
void BuildAdvancedLODScene(Scene& scene);
