#pragma once

class Scene;

// 4. 텍스처 스플래팅 (Texture Splatting, 정점 경사도/높이 기반)
//
// 3번과 같은 높이맵 지형 위에서 시작한다(카메라·높이맵 파일·펼침 파라미터 조작은
// HeightMapControlComponent 가 그대로 맡는다). 여기에 얹는 것은 "체커/고도색 대신
// 모래·잔디·바위·눈 디퓨즈 텍스처 4장을 정점의 높이와 경사도로 섞어서 그린다"는
// 부분뿐이다.
//
//   - 높이 : 정점이 이미 갖고 있는 높이(HeightMap::Evaluate 로 구운 값)를
//            0~1 로 정규화해서 구간별로 재질을 배정한다 (모래->잔디->바위->눈)
//   - 경사도 : 법선과 up 벡터의 내적(1-dot)으로 구한다. 3번 지형 생성 때 이미
//            이웃 높이의 중앙 차분으로 계산해둔 법선을 그대로 재사용하므로
//            새로 계산하는 것은 없다. 경사가 급해질수록 모래/잔디가 바위로 밀린다
//
// 텍스처 4장은 MyTerrain/textures/ 폴더에 고정된 이름(splat_sand.png 등)으로 둔다.
//
//   [카메라] W/A/S/D 이동, E/Q 상하, 마우스 우클릭 드래그로 시점 회전,
//            휠로 이동 속도, Shift 가속, R 로 초기 위치 복귀
//   [높이맵] 위/아래로 항목 선택, 왼쪽/오른쪽으로 값 조절,
//            N 다음 파일, C 고도 색상(스플래팅과 비교용), F5 다시 읽기, 0 기본값 복귀
//   [스플래팅] V 켬/끔, I/K 타일링, U/J 경사 구간, 0 스플래팅 기본값
//   [그리드] + / - 로 분할 수, [ / ] 로 셀 크기, Tab 으로 표시 모드 전환
void BuildTextureSplattingScene(Scene& scene);
