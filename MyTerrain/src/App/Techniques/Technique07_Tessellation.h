// 7. 하드웨어 테셀레이션 지형 (Hardware Tessellation)
//
// 6-1/6-2 가 "CPU 가 레벨별 인덱스를 미리 굽고 매 프레임 고르는" 접근이었다면,
// 7번은 그 선택과 이음매 처리를 통째로 GPU 테셀레이션 스테이지(HS -> 고정 기능
// 테셀레이터 -> DS)에 넘긴다.
//
//   [패치]   SetGrid 로 아주 성기게(기본 16 x 16) 만든 격자의 셀 하나하나가
//            그대로 정점 4개짜리 패치가 된다 (PatchGrid.h 참고).
//   [팩터]   HS 의 패치 상수 함수가 변(edge) 마다 카메라 거리로 테셀레이션 팩터를
//            정한다. 변 하나의 팩터를 그 변의 두 월드 좌표 끝점만으로 계산하므로,
//            그 변을 공유하는 이웃 패치도 항상 같은 값을 얻는다 -- 6-2 처럼 CPU 가
//            나서서 테두리를 다시 엮을 필요가 원천적으로 없다.
//   [디스플레이스먼트] DS 는 코너 4개를 쌍선형 보간만 하는 대신, 새로 생긴 정점마다
//            3번 기법이 쓰던 높이맵 텍스처를 다시 읽어 실제 지형 높이로 밀어 올린다
//            (그래서 3번의 HeightMapControlComponent 를 그대로 layered 로 얹어 쓴다).
//
// 구현상 처음으로 정점 셰이더 뒤에 HS/DS 스테이지가 붙는 기법이다. VS(VSPatch) 는
// 클립 공간까지 가지 않고 월드 공간에서 멈추고, 최종 좌표 변환은 DS 가 한다.
//
//   [카메라]      W/A/S/D 이동   E/Q 상하   마우스 우클릭 드래그 시점   휠 속도   Shift 가속   R 리셋
//   [높이맵]      항목 선택 ↑/↓   값 조절 ←/→   다음 파일 N   고도 색상 C   다시 읽기 F5
//   [패치 격자]   패치 개수 + / -   패치 크기 [ / ]   표시 모드 Tab
//   [테셀레이션]  디스플레이스먼트 H   파티션 모드 J   팩터 시각화 V   프리즈 F   컬링 X   패치 박스 B
//                 최대 팩터 O / P   기준 거리 ; / '
//   [공통]        기본값 복귀 0                                            [메뉴로] ESC
void BuildTessellationScene(Scene& scene);
