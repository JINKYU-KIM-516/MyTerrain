#pragma once
#include <vector>
#include <cstdint>

// 청크 테두리(링)를 이웃 청크의 레벨에 맞춰 삼각형으로 엮는 모듈.
// 6-2 고급 거리 LOD (스티칭) 에서만 쓴다.
//
// ---------------------------------------------------------------------------
// 무엇을 푸는가
// ---------------------------------------------------------------------------
// 레벨 L(스텝 s) 청크의 경계 정점은 s 간격, 이웃 레벨 L+1 청크의 경계 정점은 2s 간격이다.
// 그래서 세밀한 쪽의 홀수번째 경계 정점은 거친 쪽의 변 "위에" 떠 있는 T-junction 이 되고,
// 그 정점의 실제 높이가 거친 변의 높이와 다르면 그만큼 틈(crack)이 벌어진다.
//
// 해결은 "세밀한 쪽이 거친 쪽에 맞춰 준다" 이다 -- 세밀한 청크가 그 변의 홀수번째
// 경계 정점을 아예 쓰지 않도록 테두리를 다시 엮는다. 거친 쪽은 손대지 않으므로
// "누가 누구에게 맞출까" 하는 순환 의존이 생기지 않는다.
//
// 전제: 이웃과의 레벨 차이가 1 이하여야 한다 (TerrainLOD::ClampNeighborLevels 가 보장).
// 차이가 2 이상이면 경계 정점을 두 개 이상 버려야 해서 경우의 수가 폭발한다.
//
// ---------------------------------------------------------------------------
// 왜 미리 굽지 않고 매 프레임 만드나
// ---------------------------------------------------------------------------
// 테두리 모양은 변 4개가 각각 "이웃이 같은 레벨 / 한 단계 거침" 두 상태를 가지므로
// 16 가지다. 게다가 모서리 셀은 두 변에 동시에 걸리기 때문에 변별로 따로 구울 수도 없다.
// 레벨마다 16 가지를 다 구우면 인덱스 메모리가 기본의 7~8 배가 된다.
//
// 대신 이렇게 나눴다:
//   - 코어(테두리 한 줄을 뺀 안쪽)와 통짜 버전은 TerrainLOD 가 지금처럼 미리 굽는다.
//   - 테두리가 이웃과 어긋나는 청크만, 그 링을 매 프레임 CPU 에서 만들어
//     동적 인덱스 버퍼에 올린다.
// 레벨 영역은 넓고 경계는 얇아서 실제로 어긋나는 청크는 전체의 10~20% 수준이고,
// 링 하나는 O(청크 둘레) 라 매 프레임 비용이 아주 작다 (디버그 박스와 같은 규모).
//
// ---------------------------------------------------------------------------
// 어떻게 엮나 : 두 폐곡선의 지퍼(zip)
// ---------------------------------------------------------------------------
// 링은 "바깥 테두리 폴리라인"과 "안쪽(코어) 테두리 폴리라인" 사이의 고리 모양 영역이다.
//   - 바깥 : 청크 둘레의 정점들. 스티칭하는 변에서는 홀수번째를 건너뛴다.
//   - 안쪽 : 코어 사각형의 둘레 정점들. 항상 스텝 s 간격.
// 두 폐곡선을 둘레 매개변수 t (변 번호 + 변 안에서의 비율, 0~4) 로 나란히 놓고
// 다음 정점이 더 가까운 쪽을 한 칸씩 전진시키며 삼각형을 뱉는다. 이렇게 하면
// 모서리를 특별 취급하지 않아도 겹침/빈틈 없이 채워진다 -- 변별로 나눠 처리할 때
// 생기는 "모서리 셀이 두 변에 동시에 속하는" 문제 자체가 사라진다.
//
// 안쪽 사각형이 점 하나로 찌그러지는 경우(청크가 2x2 스텝셀일 때)는 그 점에서
// 바깥 테두리로 부채꼴을 펴는 것이 되는데, 같은 코드가 그대로 처리한다.
namespace TerrainStitch
{
    // 이웃이 "한 단계 거친" 방향 비트.
    enum EdgeBit
    {
        EdgeMinusX = 1 << 0,
        EdgeMinusZ = 1 << 1,
        EdgePlusX  = 1 << 2,
        EdgePlusZ  = 1 << 3,
        EdgeAll    = 0xF,
    };

    // 청크 [cellX0, cellX1) x [cellZ0, cellZ1) 의 테두리 링을 out 뒤에 이어 붙인다.
    //   step         : 이 청크가 지금 쓰는 레벨의 스텝 (2^level)
    //   coarserMask  : EdgeBit 조합. 해당 방향 이웃이 한 단계 거칠 때만 켠다.
    //   vertexCountX : 정점 격자의 가로 정점 수 (divisionsX + 1)
    //
    // 스티칭이 성립하지 않는 모양(청크가 스텝으로 나눠떨어지지 않거나, 한 변의
    // 스텝셀 수가 2 미만이거나 홀수이거나, 안쪽 사각형이 선분으로 눌리는 경우)에서는
    // mask 를 무시하고 평범한 링을 만든다. 그래야 어떤 설정에서도 지형에 구멍이 나지 않는다.
    // (정사각형 청크에서는 이 예외에 걸리지 않는다 -- CanStitch 주석 참고)
    void BuildRing(std::vector<uint32_t>& out, int vertexCountX,
                   int cellX0, int cellX1, int cellZ0, int cellZ1,
                   int step, int coarserMask);

    // 이 청크 모양에서 스티칭이 가능한지 (BuildRing 이 mask 를 실제로 반영하는지).
    bool CanStitch(int cellX0, int cellX1, int cellZ0, int cellZ1, int step);
}
